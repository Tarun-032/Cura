            height: 1.35,
          ),
        ),
        SizedBox(height: 10),
        _PolicyBullet(
          'Cura stores and processes your medical documents on your phone by '
          'default.',
        ),
        _PolicyBullet(
          'Cura has no accounts, ads, developer analytics, or '
          'developer-operated record server.',
        ),
        _PolicyBullet(
          'Cloud AI is optional. When enabled, minimized and redacted text is '
          'sent to the provider you choose.',
